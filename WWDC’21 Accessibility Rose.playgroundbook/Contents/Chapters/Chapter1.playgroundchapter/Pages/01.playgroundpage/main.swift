 # The Wind Rose
 ## Other names: Compas Rose or Rose of the Winds
 **Wind rose** - a concept that has existed in the world for thousands of years 👴. This simple symbol 🧭 contains many more stories, meanings, and functions than you might think 👨‍🏫. The rose, as a flower 🌹, shows the beauty of nature, and the wind, as an element 💨, inspires respect for the world around us 🌍.
 
 ## Historical Rose
 Initial mentions of the Wind Rose are dated back to the times before existence of Ancient Rome 📜. Sailors ⚓️ needed to determine the direction in which to go ⛴. Initially, they used 12 directions defined by proper names. The picture shows the classic Greek 🏛 version of the twelve-way wind rose with the direction names.
 
 ## Compass rose
 The Compas Rose as a graphic sign that shows the orientation of a map 🗺, drawing or sculpture in relation to its location on the ground 🗿. The simple wind rose shows four directions for North👆, South👇, East 👉 and West 👈 but there are also versions with eight or even sixteen and thirty-two directions 🤓. This symbol can also be found on the compass and in mobile applications 📲.
 
 ## Wind rose
 A less known type of wind rose is the pie chart 📊 that shows the wind speed in relation to a given point on the ground 🌬. Circular format shows the frequency of winds blowing from particular directions over a specified period ⛳️. These data are used to study airflow as well as forecasting the level of air pollution 😷.
 
